func (body CelestialBody) isPlanet() bool {
	switch body {
	case CelestialMercury, CelestialVenus, CelestialMars, CelestialJupiter,
		CelestialSaturn, CelestialUranus, CelestialNeptune, CelestialPluto:
		return true
	default:
		return false
	}
}

func ComputeCelestialTracks(location forecast.Location, validTimes []time.Time) ([]CelestialTrack, error) {
	if err := forecast.ValidateCoordinates(location.Latitude, location.Longitude); err != nil {
		return nil, err
	}
	if len(validTimes) == 0 {
		return nil, fmt.Errorf("celestial tracks require at least one instant")
	}
	if err := validateCelestialTrackTimes(validTimes); err != nil {
		return nil, err
	}
	tracks := make([]CelestialTrack, len(celestialBodyOrder))
	for bodyIndex, body := range celestialBodyOrder {
		distanceScale, err := celestialDistanceScale(body)
		if err != nil {
			return nil, fmt.Errorf("compute %s distance scale: %w", body, err)
		}
		tracks[bodyIndex] = CelestialTrack{
			Body: body, DistanceScale: distanceScale,
			Samples: make([]CelestialHorizontalPosition, len(validTimes)),
		}
		for timeIndex, validAt := range validTimes {
			position, err := CelestialPositionAt(location, validAt, body)
			if err != nil {
				return nil, fmt.Errorf("compute %s at %s: %w", body, validAt.Format(time.RFC3339), err)
			}
			tracks[bodyIndex].Samples[timeIndex] = position
		}
		tracks[bodyIndex].MeanDistanceClosenessPercent = meanDistanceClosenessPercent(tracks[bodyIndex].Samples)
	}
	if err := ValidateCelestialTracks(tracks, validTimes); err != nil {
		return nil, err
	}
	return tracks, nil
}

func ValidateCelestialTracks(tracks []CelestialTrack, validTimes []time.Time) error {
	if err := validateCelestialTrackTimes(validTimes); err != nil {
		return err
	}
	if len(tracks) != len(celestialBodyOrder) {
		return fmt.Errorf("celestial track count is %d, want %d", len(tracks), len(celestialBodyOrder))
	}
	for trackIndex, track := range tracks {
		body := celestialBodyOrder[trackIndex]
		if track.Body != body || len(track.Samples) != len(validTimes) {
			return fmt.Errorf("celestial track %d identity or cardinality is invalid", trackIndex)
		}
		wantScale, err := celestialDistanceScale(body)
		if err != nil {
			return fmt.Errorf("celestial track %s distance scale: %w", body, err)
		}
		if track.DistanceScale != wantScale {
			return fmt.Errorf("celestial track %s distance scale is invalid", body)
		}
		for sampleIndex, sample := range track.Samples {
			if sample.Body != body || !sample.ValidAt.Equal(validTimes[sampleIndex]) {
				return fmt.Errorf("celestial track %s sample %d identity or time is invalid", body, sampleIndex)
			}
			if err := validateCelestialPosition(sample); err != nil {
				return fmt.Errorf("celestial track %s sample %d: %w", body, sampleIndex, err)
			}
		}
		wantMean := meanDistanceClosenessPercent(track.Samples)
		if track.MeanDistanceClosenessPercent < 0 || track.MeanDistanceClosenessPercent > 100 ||
			track.MeanDistanceClosenessPercent != wantMean {
			return fmt.Errorf("celestial track %s mean distance closeness is invalid", body)
		}
	}
	return nil
}

func validateCelestialTrackTimes(validTimes []time.Time) error {
	if len(validTimes) == 0 {
		return fmt.Errorf("celestial tracks require at least one instant")
	}
	for index, validAt := range validTimes {
		utc := validAt.UTC()
		if validAt.IsZero() || utc.Minute() != 0 || utc.Second() != 0 || utc.Nanosecond() != 0 {
			return fmt.Errorf("celestial track time %d is not an exact UTC hour", index)
		}
		if err := validateCelestialEphemerisInstant(utc); err != nil {
			return fmt.Errorf("celestial track time %d: %w", index, err)
		}
		if index > 0 && utc.Sub(validTimes[index-1].UTC()) != time.Hour {
			return fmt.Errorf("celestial track times %d and %d are not exactly one hour apart", index-1, index)
		}
	}
	return nil
}

func CelestialPositionAt(location forecast.Location, at time.Time, body CelestialBody) (CelestialHorizontalPosition, error) {
	position := CelestialHorizontalPosition{ValidAt: at.UTC(), Body: body}
	if at.IsZero() {
		return position, fmt.Errorf("celestial position time is zero")
	}
	if err := validateCelestialEphemerisInstant(at); err != nil {
		return position, err
	}
	if err := forecast.ValidateCoordinates(location.Latitude, location.Longitude); err != nil {
		return position, err
	}
	if body == CelestialMoon {
		state := MoonStateAt(location, at)
		if !state.Valid {
			return position, fmt.Errorf("lunar ephemeris is unavailable")
		}
		position.AzimuthDegrees = state.AzimuthDegrees
		position.GeometricAltitudeDegrees = state.TopocentricGeometricAltitudeDegrees
		position.ApparentAltitudeDegrees = planningApparentAltitude(state.TopocentricGeometricAltitudeDegrees*degree) / degree
		position.ReferenceDistanceKM = state.EarthMoonDistanceKM
	} else {
		var coordinates equatorial
		var err error
		switch body {
		case CelestialSun:
			coordinates = sunCoordinates(at)
		case CelestialMercury, CelestialVenus, CelestialMars, CelestialJupiter, CelestialSaturn, CelestialUranus, CelestialNeptune, CelestialPluto:
			coordinates, err = planetCoordinates(at, body)
		default:
			return position, fmt.Errorf("unsupported celestial body %q", body)
		}
		if err != nil {
			return position, err
		}
		altitude, azimuth := topocentricHorizontal(at, location, coordinates)
		position.AzimuthDegrees = normalizeRadians(azimuth) / degree
		position.GeometricAltitudeDegrees = altitude / degree
		position.ApparentAltitudeDegrees = planningApparentAltitude(altitude) / degree
		position.ReferenceDistanceKM = coordinates.distance
	}
	distanceScale, err := celestialDistanceScale(body)
	if err != nil {
		return position, err
	}
	position.DistanceClosenessPercent, err = distanceClosenessPercent(position.ReferenceDistanceKM, distanceScale)
	if err != nil {
		return position, err
	}
	position.RadialVelocityKMS, err = celestialRadialVelocityKMS(at, body)
	if err != nil {
		return position, err
	}
	if body == CelestialSaturn {
		opening, openingErr := saturnRingOpeningDegrees(at)
		if openingErr != nil {
			return position, openingErr
		}
		position.SaturnRingOpeningDegrees = &opening
	}
	return position, validateCelestialPosition(position)
}

func validateCelestialEphemerisInstant(at time.Time) error {
	instant := at.UTC()
	if instant.Before(celestialEphemerisFirstInstant) || !instant.Before(celestialEphemerisLastInstant) {
		return fmt.Errorf("celestial planning ephemeris supports instants from %s through but excluding %s", celestialEphemerisFirstInstant.Format(time.DateOnly), celestialEphemerisLastInstant.Format(time.DateOnly))
	}
	return nil
}

func validateCelestialPosition(position CelestialHorizontalPosition) error {
	if position.ValidAt.IsZero() || !finite(position.AzimuthDegrees) || position.AzimuthDegrees < 0 || position.AzimuthDegrees >= 360 ||
		!finite(position.GeometricAltitudeDegrees) || position.GeometricAltitudeDegrees < -90 || position.GeometricAltitudeDegrees > 90 ||
		!finite(position.ApparentAltitudeDegrees) || position.ApparentAltitudeDegrees < -90 || position.ApparentAltitudeDegrees > 90 ||
		!finite(position.ReferenceDistanceKM) || position.ReferenceDistanceKM <= 0 ||
		!finite(position.DistanceClosenessPercent) || position.DistanceClosenessPercent < 0 || position.DistanceClosenessPercent > 100 ||
		!finite(position.RadialVelocityKMS) {
		return fmt.Errorf("%s horizontal ephemeris is outside its physical range", position.Body)
	}
	if position.Body == CelestialSaturn {
		if position.SaturnRingOpeningDegrees == nil || !finite(*position.SaturnRingOpeningDegrees) ||
			*position.SaturnRingOpeningDegrees < -90 || *position.SaturnRingOpeningDegrees > 90 {
			return fmt.Errorf("saturn ring opening is outside its physical range")
		}
	} else if position.SaturnRingOpeningDegrees != nil {
		return fmt.Errorf("%s unexpectedly carries a Saturn ring opening", position.Body)
	}
	return nil
}

func celestialDistanceScale(body CelestialBody) (CelestialDistanceScale, error) {
	scale, ok := celestialHourlyDistanceScales[body]
	if !ok {
		return CelestialDistanceScale{}, fmt.Errorf("unsupported celestial body %q", body)
	}
	wantReferenceCenter := celestialReferenceEarthCenter
	if body.isPlanet() {
		wantReferenceCenter = celestialReferenceEarthMoonBarycentre
	}
	if scale.DomainStart != celestialEphemerisFirstInstant || scale.DomainEndExclusive != celestialEphemerisLastInstant ||
		scale.SampleStepHours != 1 || !finite(scale.MinimumKM) || !finite(scale.MaximumKM) ||
		scale.MinimumKM <= 0 || scale.MaximumKM <= scale.MinimumKM || scale.ReferenceCenter != wantReferenceCenter ||
		!validDistanceScaleExtremumTime(scale.MinimumAt) || !validDistanceScaleExtremumTime(scale.MaximumAt) {
		return CelestialDistanceScale{}, fmt.Errorf("%s hourly distance scale is invalid", body)
	}
	return scale, nil
}

func validDistanceScaleExtremumTime(at time.Time) bool {
	utc := at.UTC()
	return !utc.Before(celestialEphemerisFirstInstant) && utc.Before(celestialEphemerisLastInstant) &&
		utc.Minute() == 0 && utc.Second() == 0 && utc.Nanosecond() == 0
}

func celestialReferenceDistanceKM(at time.Time, body CelestialBody) (float64, error) {
	switch body {
	case CelestialSun:
		return sunCoordinates(at).distance, nil
	case CelestialMoon:
		return moonCoordinates(at).distance, nil
	case CelestialMercury, CelestialVenus, CelestialMars, CelestialJupiter,
		CelestialSaturn, CelestialUranus, CelestialNeptune, CelestialPluto:
		coordinates, err := planetCoordinates(at, body)
		return coordinates.distance, err
	default:
		return 0, fmt.Errorf("unsupported celestial body %q", body)
	}
}

func distanceClosenessPercent(distance float64, scale CelestialDistanceScale) (float64, error) {
	if !finite(distance) || distance < scale.MinimumKM || distance > scale.MaximumKM {
		return 0, fmt.Errorf("distance %.9g km is outside the exhaustive hourly %s scale [%.9g, %.9g] km", distance, scale.ReferenceCenter, scale.MinimumKM, scale.MaximumKM)
	}
	value := 100 * (scale.MaximumKM - distance) / (scale.MaximumKM - scale.MinimumKM)
	return value, nil
}

func meanDistanceClosenessPercent(samples []CelestialHorizontalPosition) int {
	if len(samples) == 0 {
		return 0
	}
	sum := 0.0
	for _, sample := range samples {
		sum += sample.DistanceClosenessPercent
	}
	return int(math.Round(sum / float64(len(samples))))
}

func celestialRadialVelocityKMS(at time.Time, body CelestialBody) (float64, error) {
	left, right := at.Add(-30*time.Minute), at.Add(30*time.Minute)
	if left.Before(celestialEphemerisFirstInstant) {
		left, right = at, at.Add(time.Hour)
	}
	if !right.Before(celestialEphemerisLastInstant) {
		left, right = at.Add(-time.Hour), at
	}
	leftDistance, err := celestialReferenceDistanceKM(left, body)
	if err != nil {
		return 0, err
	}
	rightDistance, err := celestialReferenceDistanceKM(right, body)
	if err != nil {
		return 0, err
	}
	return (rightDistance - leftDistance) / right.Sub(left).Seconds(), nil
}

func topocentricHorizontal(at time.Time, location forecast.Location, coordinates equatorial) (float64, float64) {
	latitudeRadians := location.Latitude * degree
	rhoCosPhiPrime, rhoSinPhiPrime := wgs84ObserverFactors(location)
	sinHorizontalParallax := wgs84SemiMajorAxisKM / coordinates.distance
	hourAngle := localHourAngle(at, location.Longitude, coordinates.ra)

	a := math.Cos(coordinates.dec) * math.Sin(hourAngle)
	b := math.Cos(coordinates.dec)*math.Cos(hourAngle) - rhoCosPhiPrime*sinHorizontalParallax
	c := math.Sin(coordinates.dec) - rhoSinPhiPrime*sinHorizontalParallax
	norm := math.Sqrt(a*a + b*b + c*c)
	topocentricHourAngle := math.Atan2(a, b)
	topocentricDeclination := math.Asin(c / norm)

	altitudeRadians := altitude(topocentricHourAngle, latitudeRadians, topocentricDeclination)
	east := -math.Cos(topocentricDeclination) * math.Sin(topocentricHourAngle)
	north := math.Sin(topocentricDeclination)*math.Cos(latitudeRadians) -
		math.Cos(topocentricDeclination)*math.Cos(topocentricHourAngle)*math.Sin(latitudeRadians)
	return altitudeRadians, normalizeRadians(math.Atan2(east, north))
}

func wgs84ObserverFactors(location forecast.Location) (rhoCosPhiPrime, rhoSinPhiPrime float64) {
	latitudeRadians := location.Latitude * degree
	sinLatitude, cosLatitude := math.Sincos(latitudeRadians)
	primeVerticalRadiusKM := wgs84SemiMajorAxisKM /
		math.Sqrt(1-wgs84FirstEccentricitySquared*sinLatitude*sinLatitude)
	// The product currently has no observer-height input, so topocentric
	// parallax is evaluated on the WGS84 reference ellipsoid (h=0).
	return primeVerticalRadiusKM * cosLatitude / wgs84SemiMajorAxisKM,
		primeVerticalRadiusKM * (1 - wgs84FirstEccentricitySquared) * sinLatitude / wgs84SemiMajorAxisKM
}

func planningApparentAltitude(geometric float64) float64 {
	if geometric < -degree {
		return geometric
	}
	// Meeus/Bennett-style standard refraction. Unlike the legacy rise/set
	// helper, this path must retain the actual negative altitude down to the
	// published -1 degree applicability boundary instead of clamping it to the
	// geometric horizon.
	return geometric + 0.0002967/math.Tan(geometric+0.00312536/(geometric+0.08901179))
}

func normalizeRadians(value float64) float64 {
	value = math.Mod(value, 2*math.Pi)
	if value < 0 {
		value += 2 * math.Pi
	}
	return value
}
