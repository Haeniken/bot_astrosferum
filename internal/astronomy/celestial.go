const CelestialEphemerisVersion = "celestial-horizontal-distance-aspect-jpl-meeus-wgs84-h0-v3"

var (
	// The common reception-time domain starts one UTC day after the nominal
	// Pluto-series boundary so the retarded Pluto state remains within its
	// published source interval for every accepted instant.
	celestialEphemerisFirstInstant = time.Date(1885, time.January, 2, 0, 0, 0, 0, time.UTC)
	celestialEphemerisLastInstant  = time.Date(2050, time.January, 1, 0, 0, 0, 0, time.UTC)
)

type CelestialBody string

const (
	CelestialSun     CelestialBody = "sun"
	CelestialMoon    CelestialBody = "moon"
	CelestialMercury CelestialBody = "mercury"
	CelestialVenus   CelestialBody = "venus"
	CelestialMars    CelestialBody = "mars"
	CelestialJupiter CelestialBody = "jupiter"
	CelestialSaturn  CelestialBody = "saturn"
	CelestialUranus  CelestialBody = "uranus"
	CelestialNeptune CelestialBody = "neptune"
	CelestialPluto   CelestialBody = "pluto"
	celestialEarth   CelestialBody = "earth"
)

var celestialBodyOrder = [...]CelestialBody{
	CelestialSun,
	CelestialMoon,
	CelestialMercury,
	CelestialVenus,
	CelestialMars,
	CelestialJupiter,
	CelestialSaturn,
	CelestialUranus,
	CelestialNeptune,
	CelestialPluto,
}

func CelestialBodies() []CelestialBody {
	bodies := celestialBodyOrder
	return bodies[:]
}

type CelestialHorizontalPosition struct {
	ValidAt                  time.Time     `json:"valid_at"`
	Body                     CelestialBody `json:"body"`
	AzimuthDegrees           float64       `json:"azimuth_deg"`
	GeometricAltitudeDegrees float64       `json:"geometric_altitude_deg"`
	ApparentAltitudeDegrees  float64       `json:"apparent_altitude_deg"`
	ReferenceDistanceKM      float64       `json:"reference_distance_km"`
	DistanceClosenessPercent float64       `json:"distance_closeness_percent"`
	RadialVelocityKMS        float64       `json:"radial_velocity_km_s"`
	SaturnRingOpeningDegrees *float64      `json:"saturn_ring_opening_deg,omitempty"`
}

// CelestialDistanceScale is the deterministic model-wide geocentric distance
// range over the common half-open planning domain.  It is not a 72-hour or a
// nearest-opposition normalization.  The extrema are located from the same
// ephemeris implementation used for each published sample.
type CelestialDistanceScale struct {
	DomainStart        time.Time `json:"domain_start"`
	DomainEndExclusive time.Time `json:"domain_end_exclusive"`
	SampleStepHours    int       `json:"sample_step_hours"`
	ReferenceCenter    string    `json:"reference_center"`
	MinimumKM          float64   `json:"minimum_km"`
	MinimumAt          time.Time `json:"minimum_at"`
	MaximumKM          float64   `json:"maximum_km"`
	MaximumAt          time.Time `json:"maximum_at"`
}

type CelestialTrack struct {
	Body                         CelestialBody                 `json:"body"`
	DistanceScale                CelestialDistanceScale        `json:"distance_scale"`
	MeanDistanceClosenessPercent int                           `json:"mean_distance_closeness_percent"`
	Samples                      []CelestialHorizontalPosition `json:"samples"`
}

