export function normalizeLocale(language) {
  return typeof language === "string" && language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function createTranslator(locale) {
  const selected = MESSAGES[normalizeLocale(locale)];
  return (key, variables = {}) => {
    const template = selected[key] ?? MESSAGES.en[key] ?? key;
    return template.replace(/\{([a-z]+)\}/gi, (match, name) => (
      Object.hasOwn(variables, name) ? String(variables[name]) : match
    ));
  };
}

export function formatInstant(value, locale, timeZone, includeDate = true) {
  const options = {
    timeZone,
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  };
  if (includeDate) {
    options.day = "2-digit";
    options.month = "2-digit";
  }
  return new Intl.DateTimeFormat(locale === "ru" ? "ru-RU" : "en-GB", options).format(new Date(value));
}

export function formatDuration(seconds, locale) {
  if (!Number.isFinite(seconds)) {
    return "\u2014";
  }
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  return locale === "ru" ? `${hours} \u0447 ${minutes} \u043c\u0438\u043d` : `${hours} h ${minutes} min`;
}
